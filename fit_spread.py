"""
v0.7 spread calibration: make one grade point mean one SD of real pitchers at each level.

Targets: data/talent_spread.json (talent_spread.py), the true SD across pitchers of walk+HBP rate and strikeout rate.
Model: a pitcher's command and stuff are independent dimensions graded 1-5, 3 = level average, one point = one SD.
For the calibration staff (calib.STAFF, which reproduces each level's real averages) the engine's exact plate-appearance
evaluator gives how walk+HBP and K rates change per grade point of command and of stuff (central differences of
±DELTA). With independent unit-SD grades, the engine's implied spread across pitchers is
    SD(walk+HBP) = sqrt(dW/dcmd^2 + dW/dstuff^2),   SD(K) = sqrt(dK/dcmd^2 + dK/dstuff^2)
and the implied walk/K correlation
    corr = (dW/dcmd*dK/dcmd + dW/dstuff*dK/dstuff) / (SD(walk+HBP) * SD(K)).
cmd_scale, stuff_scale and cmd_whiff (v0.7b: how much better command adds strikeouts) are solved so both SDs and the
correlation match the real ones (fixed-point iteration with a secant step for cmd_whiff). Then fit_all.py refits each level's averages with the new scales, and this
repeats until both hold together.

Writes spread_params.py (loaded by engine.py).  Usage: python3 fit_spread.py [measure|fit] [levels...]
MLB stays at scale 1: it is only a comparison level and no per-pitcher MLB data was collected.
"""
import json, math, os, pprint, sys, time
HERE = os.path.dirname(os.path.abspath(__file__))
import engine, calib

DELTA = 0.5
TARGET = json.load(open(os.path.join(HERE, "data", "talent_spread.json")))["levels"]


def rates(level, dc=0.0, dg=0.0):
    saved = [[(p.command, p.grade) for p in w["arsenal"]] for w in calib.STAFF]
    try:
        for w in calib.STAFF:
            for p in w["arsenal"]:
                p.command += dc; p.grade += dg
        r = calib.evaluate(level)
    finally:
        for w, sv in zip(calib.STAFF, saved):
            for p, (c, g) in zip(w["arsenal"], sv):
                p.command, p.grade = c, g
    return r["BB"] + r["HBP"], r["K"]


def implied(level):
    wc1, kc1 = rates(level, dc=+DELTA); wc0, kc0 = rates(level, dc=-DELTA)
    wg1, kg1 = rates(level, dg=+DELTA); wg0, kg0 = rates(level, dg=-DELTA)
    J = {"w_cmd": (wc1 - wc0) / (2 * DELTA), "k_cmd": (kc1 - kc0) / (2 * DELTA), "w_stuff": (wg1 - wg0) / (2 * DELTA), "k_stuff": (kg1 - kg0) / (2 * DELTA)}
    sw, sk = math.hypot(J["w_cmd"], J["w_stuff"]), math.hypot(J["k_cmd"], J["k_stuff"])
    corr = (J["w_cmd"] * J["k_cmd"] + J["w_stuff"] * J["k_stuff"]) / (sw * sk)
    return J, sw, sk, corr


def set_scales(level, sc, ss, cw=0.0):
    for l in ([level, "college"] if level == "college_d1" else [level]):
        engine.LEVEL[l]["cmd_scale"] = sc; engine.LEVEL[l]["stuff_scale"] = ss; engine.LEVEL[l]["cmd_whiff"] = cw


def k_cmd_target(J, tc):
    """The strikeouts-per-command-point that gives the real walk/K correlation tc, holding the other three slopes."""
    wc, ws, ks = J["w_cmd"], J["w_stuff"], J["k_stuff"]
    kc = J["k_cmd"]
    for _ in range(50):     # corr(kc) = (wc*kc + ws*ks) / (sw * sqrt(kc^2 + ks^2)); fixed point on kc
        sw = math.hypot(wc, ws)
        num = tc * sw * math.hypot(kc, ks) - ws * ks
        kc = num / wc
    return kc


def save(params):
    with open(os.path.join(HERE, "spread_params.py"), "w") as f:
        f.write('"""Generated by fit_spread.py. v0.7: one grade point = one SD of real pitchers at the level (talent_spread.py)."""\n')
        f.write("SPREAD_FIT = " + pprint.pformat(params, width=110) + "\n")


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "measure"
    levels = sys.argv[2:] or ["college_d3", "college_d1", "hs"]
    try:
        from spread_params import SPREAD_FIT
        params = {k: dict(v) for k, v in SPREAD_FIT.items()}
    except ImportError:
        params = {}
    for lvl in levels:
        t = TARGET[lvl]
        tw, tk = t["walk_hbp"]["true_sd"], t["k"]["true_sd"]
        sc, ss = params.get(lvl, {}).get("cmd_scale", 1.0), params.get(lvl, {}).get("stuff_scale", 1.0)
        cw = params.get(lvl, {}).get("cmd_whiff", 0.0)
        tc = t["corr_walk_k"]
        set_scales(lvl, sc, ss, cw)
        J, sw, sk, corr = implied(lvl)
        print(f"{lvl}: scales {sc:.3f}/{ss:.3f} -> SD walk {sw:.4f} (real {tw:.4f}), SD K {sk:.4f} (real {tk:.4f}), corr {corr:+.2f} (real {t['corr_walk_k']:+.2f})  {json.dumps({k: round(v, 4) for k, v in J.items()})}", flush=True)
        if mode != "fit":
            continue
        slope = -0.077 * max(1.0, sc / 4.1)          # strikeouts per point of command, per unit of cmd_whiff (measured at D3)
        for it in range(8):
            # each scale mostly drives its own rate (update multiplicatively, damped); cmd_whiff sets how much command
            # adds strikeouts, which is what sets the walk/K correlation (v0.7b)
            want = k_cmd_target(J, tc)
            cw_new = cw + (want - J["k_cmd"]) / slope
            sc *= (tw / sw) ** 0.9; ss *= (tk / sk) ** 0.9
            prev = (cw, J["k_cmd"])
            cw = cw_new
            set_scales(lvl, sc, ss, cw)
            J, sw, sk, corr = implied(lvl)
            if abs(cw - prev[0]) > 1e-6:      # secant update of the slope
                slope = (J["k_cmd"] - prev[1]) / (cw - prev[0]) if abs(J["k_cmd"] - prev[1]) > 1e-6 else slope
            print(f"   iter {it + 1}: scales {sc:.3f}/{ss:.3f}, cmd_whiff {cw:.3f} -> SD walk {sw:.4f}, SD K {sk:.4f}, corr {corr:+.2f}", flush=True)
            if abs(sw / tw - 1) < 0.03 and abs(sk / tk - 1) < 0.03 and abs(corr - tc) < 0.05:
                break
        params[lvl] = {"cmd_scale": round(sc, 4), "stuff_scale": round(ss, 4), "cmd_whiff": round(cw, 4), "target_corr": tc, "sd_walk": round(sw, 4), "sd_k": round(sk, 4), "corr": round(corr, 3),
                       "target_walk": tw, "target_k": tk, **{k: round(v, 5) for k, v in J.items()}}
        save(params)
    if mode == "fit":
        print("saved spread_params.py")


if __name__ == "__main__":
    main()
