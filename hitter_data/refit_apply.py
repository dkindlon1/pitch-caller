"""v1.3 Part 2.5: write hitter_data/refit.py's refit numbers into both engines' literals (engine.py and app/engine.js).

  python3 -m hitter_data.refit_apply [--dry]     reads {DATA}/refit/<fit>.json, edits the literals in place

Only the value literals change (each replacement must match exactly once; the script stops otherwise). The other refit
groups ship through their own generators: fit_v08.json (hitter_data/refit_seq.py), the profile tables
(hitter_data/refit_profiles.py), the MLB targets and the calibration chain (hitter_data/refit_mlb_targets.py,
hitter_data/refit_chain.py). app/engine_data.json is regenerated by app/export_data.py afterwards.
"""
import json
import os
import re
import sys

from . import DATA

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(DATA, "refit")


def load(name):
    with open(os.path.join(RES, f"{name}.json")) as fh:
        return json.load(fh)


def num(x):
    """A literal the way the shipped files write it: shortest round-trip repr, at least one decimal."""
    s = repr(float(x))
    return s


def side_json(d):
    return json.dumps({o: {c: float(v) for c, v in d[o].items()} for o in ("hard", "whiff", "swing")})


def power_hr_value():
    """POWER_HR is per power-grade point, and one point = one HARD_SD of hitters' hard-hit share (engine.py comment at
    POWER_HR). refit_power_hr's coefficient is per SD of its own power measure (power_sd_raw), so it is restated per
    HARD_SD (the refit value from hitter_data/refit_mlb_targets.py when present)."""
    p = load("power_hr")
    try:
        hard_sd = load("mlbt")["HARD_SD"]
    except OSError:
        hard_sd = p["power_sd_raw"]
    return round(p["coef_raw"] * hard_sd / p["power_sd_raw"], 3)


def edits():
    out = []   # (file, pattern, replacement)
    if os.path.exists(os.path.join(RES, "approach.json")):
        a = load("approach")["new"]
        out += [("engine.py", r'^HIT_FIT = \{"approach": [-0-9.]+\}', f'HIT_FIT = {{"approach": {num(a)}}}'),
                ("app/engine.js", r'const HIT_FIT = \{ approach: [-0-9.]+ \};', f'const HIT_FIT = {{ approach: {num(a)} }};')]
    if os.path.exists(os.path.join(RES, "landing.json")):
        n = load("landing")["new"]
        out += [("engine.py", r'^LAND_K = [0-9.]+\nLAND_GAIN = [0-9.]+$', f'LAND_K = {num(n["K"])}\nLAND_GAIN = {num(n["GAIN"])}'),
                ("app/engine.js", r'const LAND_K = [0-9.]+, LAND_GAIN = [0-9.]+,',
                 f'const LAND_K = {num(n["K"])}, LAND_GAIN = {num(n["GAIN"])},')]
    if os.path.exists(os.path.join(RES, "hbp_bands.json")):
        b = load("hbp_bands")["new"]
        py = "(" + ", ".join(f"({num(x)}, {num(v)})" for x, v in b) + ")"
        js = "[" + ", ".join(f"[{num(x)}, {num(v)}]" for x, v in b) + "]"
        out += [("engine.py", r'^GEO_HBP_BANDS = \(\(.*\)\)$', f'GEO_HBP_BANDS = {py}'),
                ("app/engine.js", r'const GEO_HBP_BANDS = \[\[.*\]\];', f'const GEO_HBP_BANDS = {js};')]
    if os.path.exists(os.path.join(RES, "mm.json")):
        m = load("mm")["new"]
        out += [("engine.py", r'^MM = dict\(succ=[-0-9.]+, succ_cap=4, hard=[-0-9.]+, hard_cap=2\)',
                 f'MM = dict(succ={num(m["succ"])}, succ_cap=4, hard={num(m["hard"])}, hard_cap=2)'),
                ("app/engine.js", r'const MM = \{ succ: [-0-9.]+, succ_cap: 4, hard: [-0-9.]+, hard_cap: 2 \};',
                 f'const MM = {{ succ: {num(m["succ"])}, succ_cap: 4, hard: {num(m["hard"])}, hard_cap: 2 }};')]
    if os.path.exists(os.path.join(RES, "side.json")):
        s = side_json(load("side")["new"])
        out += [("engine.py", r'^SIDE = \{"hard".*\}\}$', f'SIDE = {s}'),
                ("app/engine.js", r'const SIDE = \{"hard".*\}\};', f'const SIDE = {s};')]
    if os.path.exists(os.path.join(RES, "power_hr.json")):
        p = power_hr_value()
        out += [("engine.py", r'^POWER_HR = [0-9.]+$', f'POWER_HR = {num(p)}'),
                ("app/engine.js", r'const POWER_HR = [0-9.]+;', f'const POWER_HR = {num(p)};')]
    if os.path.exists(os.path.join(RES, "hbp_loc_apply.json")):
        h = load("hbp_loc_apply")["new"]
        py = ", ".join(f'"{k}": {num(v)}' for k, v in h.items())
        js = ", ".join((f'"{k}"' if "-" in k else k) + f": {num(v)}" for k, v in h.items())
        out += [("engine.py", r'^HBP_LOC = \{[^}]*\}', "HBP_LOC = {" + py + "}"),
                ("app/engine.js", r'const HBP_LOC = \{[^}]*\};', "const HBP_LOC = { " + js + " };")]
    return out


def apply(dry=False):
    texts = {}
    for f, pat, rep in edits():
        p = os.path.join(ROOT, f)
        if f not in texts:
            with open(p, encoding="utf-8", newline="") as fh:
                texts[f] = fh.read()
        t = texts[f]
        found = re.findall(pat, t, flags=re.M)
        if len(found) != 1:
            raise SystemExit(f"{f}: pattern {pat!r} matched {len(found)} times; refusing")
        texts[f] = re.sub(pat, lambda _m: rep, t, count=1, flags=re.M)
        print(f"{f}: {found[0][:90]}{'...' if len(found[0]) > 90 else ''}\n   -> {rep[:90]}{'...' if len(rep) > 90 else ''}")
    if not dry:
        for f, t in texts.items():
            with open(os.path.join(ROOT, f), "w", encoding="utf-8", newline="") as fh:
                fh.write(t)


if __name__ == "__main__":
    apply("--dry" in sys.argv)
