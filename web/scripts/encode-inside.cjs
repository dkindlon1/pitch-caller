// Turns the offline render (scripts/render-inside.cjs) into the site's frames and data:
//   public/media/film/inside/scene-<set>/NNNN.webp   and   content/inside-scene.ts (framing, zone box, label anchors)
//   node scripts/encode-inside.cjs [quality]
const sharp = require(process.env.SHARP || "sharp");
const fs = require("fs"), path = require("path");
const SRC = process.env.RENDER_OUT || "/home/claude/inside_render/out4";
const WEB = path.join(__dirname, "..");
const Q = +(process.argv[2] || 78);
const IDS = ["pitcher", "hitter", "game", "umpire", "pick"];
(async () => {
  const sets = {};
  for (const set of ["wide", "tablet", "phone"]) {
    const dir = path.join(SRC, set), info = JSON.parse(fs.readFileSync(path.join(dir, "info.json"), "utf8"));
    const out = path.join(WEB, "public/media/film/inside", "scene-" + set);
    fs.mkdirSync(out, { recursive: true });
    const anchors = Object.fromEntries(IDS.map((id) => [id, []]));
    let bytes = 0;
    for (let i = 0; i < info.frames; i++) {
      const n = String(i + 1).padStart(4, "0"), png = path.join(dir, n + ".png");
      if (!fs.existsSync(png)) { if (!process.env.PARTIAL) throw new Error("missing " + png); IDS.forEach((id) => anchors[id].push(null)); continue; }
      const dst = path.join(out, n + ".webp");
      if (!fs.existsSync(dst) || fs.statSync(dst).mtimeMs < fs.statSync(png).mtimeMs || process.env.FORCE)
        await sharp(png).webp({ quality: Q, effort: 6, smartSubsample: true }).toFile(dst);
      bytes += fs.statSync(dst).size;
      const A = JSON.parse(fs.readFileSync(path.join(dir, n + ".json"), "utf8"));
      for (const a of A) anchors[a.id].push(a.show ? [+(a.x / info.lw).toFixed(4), +(a.y / info.lh).toFixed(4)] : null);
    }
    sets[set] = { lw: info.lw, lh: info.lh, frames: info.frames, zone: { cx: +info.zone.cx.toFixed(2), cy: +info.zone.cy.toFixed(2), zw: +info.zone.zw.toFixed(2), zh: +info.zone.zh.toFixed(2) }, anchors };
    console.log(set, info.frames, "frames", (bytes / 1048576).toFixed(1) + "MB");
  }
  const ts = `// Generated by scripts/encode-inside.cjs from the offline render of render/insideScene.ts. Do not edit.
// Per screen shape: the screen the shot was composed for (lw x lh CSS px), the zone's box on it when the shot looks
// straight down (the site docks the app's zone onto it), and where each label points per frame (fractions of lw and lh;
// null while hidden).
export type SceneSet = { lw: number; lh: number; frames: number; zone: { cx: number; cy: number; zw: number; zh: number }; anchors: Record<string, ([number, number] | null)[]> };
export const SCENE: Record<"wide" | "tablet" | "phone", SceneSet> = ${JSON.stringify(sets)};
`;
  fs.writeFileSync(path.join(WEB, "content/inside-scene.ts"), ts);
})();
