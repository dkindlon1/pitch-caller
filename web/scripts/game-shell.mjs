// Builds the installable game app at /app/game/ from the tested single-file build (app/dist/pitch-caller.html):
// the page itself, wrapped with its manifest and the service worker glue, and the service worker, whose cache name is
// the page's content hash so every new build is a new version. Run before `next build` (npm run build does).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = readFileSync(join(here, "../../app/dist/pitch-caller.html"), "utf8");
const out = join(here, "../public/app/game");

// The page registers the worker and decides when a new version may take over: never during a live game (spec A6).
const glue = `<script>
if (location.pathname === "/app/game") location.replace("/app/game/" + location.search + location.hash);   // inside the worker's scope
window.PC_CONFIG_URL = "/app/game/config.json";
(function () {
  if (!("serviceWorker" in navigator)) return;
  var reloading = false;
  navigator.serviceWorker.addEventListener("controllerchange", function () { if (reloading) return; reloading = true; location.reload(); });
  navigator.serviceWorker.register("/app/game/sw.js", { scope: "/app/game/" }).then(function (reg) {
    function live() { try { return typeof G === "function" && !!G().dbId; } catch (e) { return false; } }
    function apply() {
      var w = reg.waiting;
      if (!w || !navigator.serviceWorker.controller) return;
      if (live()) { window.PC_UPDATE_WAITING = true; return; }        // after this game: checked again below
      w.postMessage("skipWaiting");
    }
    window.PC_APPLY_UPDATE = apply;
    reg.addEventListener("updatefound", function () {
      var n = reg.installing;
      if (n) n.addEventListener("statechange", function () { if (n.state === "installed") apply(); });
    });
    apply();
    setInterval(apply, 30000);
    document.addEventListener("visibilitychange", function () { if (document.visibilityState === "visible") { reg.update().catch(function () {}); apply(); } });
  }).catch(function (e) { console.warn("service worker", e); });
})();
</script>`;

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#07090C">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="PitchIQ">
<link rel="manifest" href="/app/game/manifest.webmanifest">
<link rel="apple-touch-icon" href="/app/game/apple-touch-icon.png">
<title>PitchIQ Game</title>
</head>
<body>
${app}
${glue}
</body>
</html>
`;
const version = createHash("sha256").update(page).digest("hex").slice(0, 16);

const sw = `// PitchIQ game app service worker, version ${version} (generated by web/scripts/game-shell.mjs).
// The app and its icons are cached when it's installed, so it opens with no signal. A new version installs in the
// background and waits; the page tells it to take over only when no game is live.
const CACHE = "pitchiq-game-${version}";
const SHELL = ["/app/game/", "/app/game/manifest.webmanifest", "/app/game/icon-192.png", "/app/game/icon-512.png", "/app/game/apple-touch-icon.png"];
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL))); });
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("pitchiq-game-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("message", (e) => { if (e.data === "skipWaiting") self.skipWaiting(); });
self.addEventListener("fetch", (e) => {
  const u = new URL(e.request.url);
  if (e.request.method !== "GET" || u.origin !== location.origin || !u.pathname.startsWith("/app/game/")) return;
  // the project settings: fresh when there's a signal, the last copy when there isn't
  if (u.pathname === "/app/game/config.json") {
    e.respondWith(fetch(e.request).then((r) => { if (r.ok) caches.open(CACHE).then((c) => c.put(e.request, r.clone())); return r; }).catch(() => caches.match(e.request)));
    return;
  }
  // the app itself: always this version's copy (an update comes as a new worker, never mid-game)
  if (e.request.mode === "navigate") { e.respondWith(caches.match("/app/game/").then((r) => r || fetch(e.request))); return; }
  e.respondWith(caches.match(e.request).then((r) => r || fetch(e.request)));
});
`;
writeFileSync(join(out, "index.html"), page);
writeFileSync(join(out, "sw.js"), sw);
console.log(`game app ${version}: ${Math.round(page.length / 1024)} KB`);
