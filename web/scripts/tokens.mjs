// Floodlight tokens: one source (web/lib/tokens/floodlight.json), two generated stylesheets.
//   web/app/floodlight.css      the marketing site and the portal import this (variables on .pq)
//   app/assets/floodlight.css   inlined into the static game app by app/build.py (variables on :root, plus the day theme)
// Run `node web/scripts/tokens.mjs` after editing the JSON. `--check` writes nothing and exits 1 if a file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = join(here, "../lib/tokens/floodlight.json");
export const WEB_OUT = join(here, "../app/floodlight.css");
export const APP_OUT = join(here, "../../app/assets/floodlight.css");

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");
const lines = (obj, pre = "") => Object.entries(obj).map(([k, v]) => `  --${pre}${k}: ${v};`);
// colours that get used at part strength also ship as "r g b", for rgb(var(--x-rgb) / 0.14)
const RGB = ["bg", "panel", "text", "weigh", "land", "alert"];
const theme = (t) => [...lines(t), ...RGB.map((k) => `  --${k}-rgb: ${rgb(t[k])};`)];

export function build(tokens = JSON.parse(readFileSync(SOURCE, "utf8"))) {
  const { brand, night, day, type, glass, motion, appMotion } = tokens;
  const head = (what) => `/* GENERATED by web/scripts/tokens.mjs from web/lib/tokens/floodlight.json. Do not edit: ${what} */\n`;
  const shared = [
    "  /* brand */", ...lines(brand), `  --chalk-rgb: ${rgb(brand.chalk)};`, `  --glow-rgb: ${rgb(brand.glow)};`, `  --call-rgb: ${rgb(brand.call)};`, `  --ground-rgb: ${rgb(brand.ground)};`, `  --midnight-rgb: ${rgb(brand.midnight)};`,
    "  --line: rgba(236, 235, 230, 0.14);",
    "  --blend: linear-gradient(90deg in oklab, var(--glow), var(--call));",
    "  /* type */", ...lines(type),
    "  /* glass */", ...lines(glass),
    "  /* motion */", ...lines(motion), ...lines(appMotion),
  ];
  const web = head("the site (site.css) and the portal (portal.css) both read these.")
    + `.pq {\n${shared.join("\n")}\n  /* the app's working set (night) */\n${theme(night).join("\n")}\n}\n`;
  const app = head("app/build.py inlines this into the game app.")
    + `:root {\n${shared.join("\n")}\n  /* night */\n${theme(night).join("\n")}\n}\n:root[data-theme="day"] {\n${theme(day).join("\n")}\n}\n`;
  return { web, app };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { web, app } = build();
  if (process.argv.includes("--check")) {
    const stale = [[WEB_OUT, web], [APP_OUT, app]].filter(([p, s]) => { try { return readFileSync(p, "utf8") !== s; } catch { return true; } }).map(([p]) => p);
    if (stale.length) { console.error("stale token files (run node web/scripts/tokens.mjs):\n  " + stale.join("\n  ")); process.exit(1); }
    console.log("tokens: generated files match the source");
  } else { writeFileSync(WEB_OUT, web); writeFileSync(APP_OUT, app); console.log("tokens: wrote", WEB_OUT, "and", APP_OUT); }
}
