"""v0.8 (8.2) hitter grade effects per level -> hitter_spread_params.py (never spread_params.py).
Targets (assumption until hitter data exists: hitters spread like pitchers): one contact point lowers the strikeout
rate by the level's sd_k, one discipline point raises the walk rate (BB + HBP) by sd_walk (spread_params.py), one power
point raises the hard-contact share of balls in play by 0.03. MLB uses D1's values. Same machinery as fit_spread.py
(calib.evaluate over the calibration staff and lineups), the call mix held fixed (policy cache) so the fit measures the
grade's own effect. usage: python3 fit_hitter_spread.py"""
import os, pprint
import engine as e, calib
from spread_params import SPREAD_FIT

HERE = os.path.dirname(os.path.abspath(__file__))
e.set_flags(**e.FLAGS_V07)
e.set_flags(hitter_grades=True)


def rates(level, cache, c=3, w=3, d=3):
    e.GRADES_OVERRIDE = {"c": c, "w": w, "d": d}
    try:
        r = calib.evaluate(level, policy_cache=cache)
        raw = dict(calib._LAST_RAW)
    finally:
        e.GRADES_OVERRIDE = None
    bip = raw["weak"] + raw["solid"] + raw["hard"]
    return r["K"], r["BB"] + r["HBP"], raw["hard"] / bip


def fit(level):
    sp = SPREAD_FIT[level]
    tg = {"g_c": sp["sd_k"], "g_d": sp["sd_walk"], "g_w": 0.03}
    g = {"g_c": 0.25, "g_w": 0.25, "g_d": 0.25}
    cache = {}
    for _ in range(3):
        e.P08.update(g)
        k1, _, _ = rates(level, cache, c=3.5); k0, _, _ = rates(level, cache, c=2.5)
        _, b1, _ = rates(level, cache, d=3.5); _, b0, _ = rates(level, cache, d=2.5)
        _, _, h1 = rates(level, cache, w=3.5); _, _, h0 = rates(level, cache, w=2.5)
        slope = {"g_c": k0 - k1, "g_d": b1 - b0, "g_w": h1 - h0}      # per grade point, sign-corrected
        g = {k: g[k] * tg[k] / slope[k] for k in g}
        print(level, {k: round(v, 4) for k, v in g.items()}, "slopes", {k: round(v, 4) for k, v in slope.items()}, flush=True)
    return g, slope


out = {}
for lvl in ("hs", "college_d3", "college_d1"):
    g, slope = fit(lvl)
    out[lvl] = {k: round(v, 4) for k, v in g.items()}
    out[lvl]["targets"] = {"sd_k": SPREAD_FIT[lvl]["sd_k"], "sd_walk": SPREAD_FIT[lvl]["sd_walk"], "hard": 0.03}
out["travel"] = dict(out["hs"]); out["mlb"] = dict(out["college_d1"]); out["college"] = dict(out["college_d1"])
with open(os.path.join(HERE, "hitter_spread_params.py"), "w") as f:
    f.write('"""Generated by fit_hitter_spread.py (v0.8, spec 8.2): hitter grade logit effects per level."""\nHITTER_SPREAD = ')
    f.write(pprint.pformat(out) + "\n")
print("wrote hitter_spread_params.py")
