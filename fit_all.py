"""Fit v0.6 outcome shifts and in-play tables. Writes outcome_params.py.
MLB: all seven shifts vs MLB pitch-level + per-PA rates (fit once, stored in fit_mlb.json; refit with --mlb).
College/HS: hitters swing and make contact like the MLB fit (no public amateur pitch-level averages);
fit level wildness, whiff level (in and out of the zone together) and HBP to each level's K/BB/HBP."""
import json, pprint, sys, time
import calib
from calib import fit, fit_inplay, show, OUTCOME_ADJ, IN_PLAY_BY_LEVEL, RV

t0 = time.time()
saved = json.load(open("fit_mlb.json"))
OUT, INP = dict(saved["OUT"]), {k: {c: tuple(v) for c, v in t.items()} for k, t in saved["INP"].items()}
OUTCOME_ADJ["mlb"].update(OUT["mlb"]); IN_PLAY_BY_LEVEL["mlb"] = INP["mlb"]


def save():
    with open("outcome_params.py", "w") as f:
        f.write('"""Generated by fit_all.py (calib.py). v0.6 outcome-model fit by level.\n'
                'OUTCOME_FIT: logit shifts so the engine + simulator reproduce real K/BB/HBP (and MLB pitch-level rates).\n'
                'IN_PLAY_FIT: per-ball-in-play outcomes (out, 1B, 2B, 3B, HR, error) refit to real hit mix."""\n')
        clean = {l: {k: round(float(v), 4) for k, v in d.items()} for l, d in OUT.items()}
        f.write("OUTCOME_FIT = " + pprint.pformat(clean, width=110) + "\n")
        f.write("IN_PLAY_FIT = " + pprint.pformat(INP, width=110) + "\n")


save()
show("mlb", "mlb (stored fit)")
m = OUT["mlb"]

# v1.0 3.7 (Drew, Nov 10): --mlb refits the MLB level too. MLB is normally a CHECK level -- its shifts were fitted
# once against MLB pitch-level rates and stored in fit_mlb.json -- but Phase 3.7's usage prior moved the call mix
# enough that the MLB per-PA strikeout rate fell 1.1 points below real, and Drew chose to refit rather than leave the
# check red. It fits the same three shifts the amateur levels fit (wild, wz, hbp, with wo tied to wz), keeps the
# pitch-level-fitted cmd/zsw/osw/cs, and leaves the MLB in-play table alone, so this changes the outcome shifts only.
# The new values are written back into fit_mlb.json as well, or the next plain `fit_all.py` run would revert them.
if "--mlb" in sys.argv:
    tg = {k: RV["mlb_check"][k] for k in ("K", "BB", "HBP")}
    start = {"wild": OUTCOME_ADJ["mlb"].get("wild", 0.15), "wz": m["wz"], "hbp": m["hbp"]}
    for outer in range(2):
        start = fit("mlb", ["wild", "wz", "hbp"], tg, {}, start=start, tie={"wo": ("wz", m["wo"] - m["wz"])})
        OUT["mlb"] = dict(OUTCOME_ADJ["mlb"])
        show("mlb", f"mlb pass {outer+1}")
        save()
    saved["OUT"]["mlb"] = {k: float(v) for k, v in OUT["mlb"].items()}
    json.dump(saved, open("fit_mlb.json", "w"), indent=1, sort_keys=True)
    print(f"[{time.time()-t0:.0f}s] target K {tg['K']:.1%} BB {tg['BB']:.1%} HBP {tg['HBP']:.1%}; "
          "rewrote fit_mlb.json", flush=True)
    m = OUT["mlb"]

levels = [a for a in sys.argv[1:] if not a.startswith("--")] or ["college_d1", "college_d3", "hs"]
for lvl in levels:
    key = lvl
    tg = {k: RV[key][k] for k in ("K", "BB", "HBP")}
    OUTCOME_ADJ[lvl].update({k: m[k] for k in ("cmd", "zsw", "osw", "cs")})
    start = {"wild": 0.15, "wz": m["wz"], "hbp": 0.12}
    for outer in range(2):
        r = fit(lvl, ["wild", "wz", "hbp"], tg, {}, start=start, tie={"wo": ("wz", m["wo"] - m["wz"])})
        start = r
        OUT[lvl] = dict(OUTCOME_ADJ[lvl])
        tab, mix, target, model = fit_inplay(lvl, key)
        INP[lvl] = tab
        print(f"  {lvl} contact mix", {k: round(float(v), 3) for k, v in mix.items()})
        show(lvl, f"{lvl} pass {outer+1}")
        save()
    print(f"[{time.time()-t0:.0f}s] target K {tg['K']:.1%} BB {tg['BB']:.1%} HBP {tg['HBP']:.1%}", flush=True)
print("done")
