const { chromium } = require("playwright");
const path = require("path");
(async () => {
  const b = await chromium.launch(); const errs = [];
  const page = await b.newPage({ viewport: { width: 1180, height: 820 } });
  page.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); }); page.on("pageerror", (e) => errs.push(String(e)));
  const html = require("fs").readFileSync(path.join(__dirname, "dist/pitch-caller.html"), "utf8");
  await page.setContent(`<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"></head><body>${html}</body></html>`, { waitUntil: "networkidle" });
  await page.waitForTimeout(500);
  const call = async () => (await page.locator(".pitch").innerText()) + " / " + (await page.locator(".spot").innerText());
  console.log("first call:", await call());
  await page.keyboard.press("b"); await page.waitForTimeout(200);
  await page.locator(".key", { hasText: "Swing and miss" }).click(); await page.locator(".lv-tray .rd", { hasText: "Late" }).click(); await page.waitForTimeout(200);
  await page.keyboard.press("f"); await page.keyboard.press("Enter"); await page.waitForTimeout(200);
  await page.locator(".key", { hasText: "In play" }).click(); await page.locator(".lv-tray .ct", { hasText: "Hard" }).click(); await page.locator(".lv-tray .out", { hasText: "Double" }).click(); await page.waitForTimeout(200);
  await page.keyboard.press("b"); await page.waitForTimeout(200);
  await page.keyboard.press("c"); await page.waitForTimeout(200);
  console.log("log rows:", await page.locator(".log-row").count(), "| count:", (await page.locator(".cell .v").first().innerText()).split("\n")[0]);
  await page.screenshot({ path: path.join(__dirname, "v3_1180.png") });
  await page.screenshot({ path: path.join(__dirname, "v3_1180_full.png"), fullPage: true });
  await page.getByRole("button", { name: "Call my own" }).click();
  await page.locator(".pick .seg").first().locator("button").nth(1).click();
  await page.locator(".pick .seg").nth(1).locator("button", { hasText: "Chase it" }).click();
  await page.locator(".pick .go").click(); await page.waitForTimeout(150);
  console.log("coach call:", await call(), "|", await page.locator(".why").innerText());
  await page.getByRole("button", { name: "Correct" }).click(); await page.waitForTimeout(100);
  await page.locator(".toggles button", { hasText: "3rd" }).click(); await page.waitForTimeout(250);
  console.log("runners:", await page.locator(".lv-strip .bases").getAttribute("aria-label"));
  await page.getByRole("button", { name: "Done" }).click();
  await page.locator(".tabs button", { hasText: "Setup" }).click(); await page.waitForTimeout(150);
  await page.screenshot({ path: path.join(__dirname, "v3_setup.png"), fullPage: true });
  await page.locator(".tabs button", { hasText: "Game" }).click(); await page.waitForTimeout(250);
  let n = 0; while (!(await page.locator(".done").count()) && n < 14) { await page.keyboard.press("c"); await page.waitForTimeout(90); n++; }
  console.log("inning over after", n);
  await page.setViewportSize({ width: 820, height: 1180 }); await page.waitForTimeout(150);
  await page.getByRole("button", { name: /Take the field/ }).click(); await page.waitForTimeout(300);
  await page.emulateMedia({ colorScheme: "dark" }); await page.waitForTimeout(100);
  await page.screenshot({ path: path.join(__dirname, "v3_820_dark.png") });
  await page.emulateMedia({ colorScheme: "light" });
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(200);
  console.log("phone scrollWidth:", await page.evaluate(() => document.documentElement.scrollWidth));
  await page.screenshot({ path: path.join(__dirname, "v3_390.png"), fullPage: true });
  const fontOk = await page.evaluate(() => document.fonts.check('700 40px "Saira"'));
  console.log("Saira loaded:", fontOk, "| errors:", errs.length ? errs : "none");
  await b.close();
})();
